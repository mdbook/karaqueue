"""Resolve container dependencies to wheel hashes, or validate the committed lock.

Resolution runs on Python 3.12/Linux, just like the container. No source builds or
extra resolver dependency are needed. Publishing a refreshed lock is a human step.
"""
import hashlib
import re
import subprocess
import sys
import tempfile
from email.parser import BytesParser
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock"
ENTRY = re.compile(r"[a-z0-9][a-z0-9.-]*==[^\s;]+ --hash=sha256:[0-9a-f]{64}")


def wheel_lock(directory):
    entries = {}
    for wheel in sorted(directory.glob("*.whl")):
        with ZipFile(wheel) as archive:
            # Top-level dist-info only: some wheels vendor other packages' dist-info dirs.
            metadata, = [name for name in archive.namelist() if name.endswith(".dist-info/METADATA") and name.count("/") == 1]
            package = BytesParser().parsebytes(archive.read(metadata))
        name = re.sub(r"[-_.]+", "-", package["Name"]).lower()
        if name in entries:
            raise ValueError("multiple wheels for " + name)
        digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
        entries[name] = f"{name}=={package['Version']} --hash=sha256:{digest}"
    if not entries:
        raise ValueError("resolver returned no wheels")
    return "# Python 3.12 Linux container dependencies; generated by ci/lock.py resolve\n" + "\n".join(
        entries[name] for name in sorted(entries)
    ) + "\n"


def check(text):
    entries = [line for line in text.splitlines() if line and not line.startswith("#")]
    if not entries or any(not ENTRY.fullmatch(line) for line in entries):
        raise ValueError("missing hash lock: run the scheduled resolver and commit its requirements.lock artifact")
    names = [line.split("==", 1)[0] for line in entries]
    if len(names) != len(set(names)):
        raise ValueError("duplicate locked package")


def resolve():
    import tomllib  # The resolver job uses Python 3.12, not the app's Python 3.9 minimum.

    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    # setuptools is locked too: install the local app without build isolation or dependencies.
    requirements = project["project"]["dependencies"] + ["yt-dlp[default,deno]", "setuptools>=68"]
    with tempfile.TemporaryDirectory(dir=ROOT) as directory:
        subprocess.run([
            sys.executable, "-m", "pip", "download", "--only-binary=:all:",
            "--no-cache-dir", "--dest", directory, *requirements,
        ], check=True, timeout=240)
        text = wheel_lock(Path(directory))
    check(text)
    LOCK.write_text(text)


if __name__ == "__main__":
    if sys.argv[1:] == ["resolve"]:
        resolve()
    elif sys.argv[1:] == ["check"]:
        check(LOCK.read_text())
    else:
        raise SystemExit("usage: python ci/lock.py resolve|check")
